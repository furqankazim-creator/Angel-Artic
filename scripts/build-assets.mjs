// Builds bundled voice clips (macOS `say` + afconvert) and Twemoji PNGs (CC-BY 4.0), plus the require() maps.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const files = ['src/data/sounds.ts', 'src/data/extras.ts', 'src/screens/Talk.tsx', 'src/components/Mascot.tsx', 'src/data/adventure.ts', 'src/data/curriculum.ts', 'src/data/levels.ts', 'src/data/scenes.ts', 'src/data/promo.ts', 'src/screens/AngelTalkPromo.tsx', 'src/data/talkBoards.ts'].filter(existsSync);
const src = files.map((f) => readFileSync(f, 'utf8')).join('\n');
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');

// ---- voice ----
const texts = new Map(); // slug -> {text, slow}
const tuple = /\['([a-z]+)','([^']+)','([^']+)'\]/g;
for (const m of readFileSync('src/data/sounds.ts', 'utf8').matchAll(tuple)) {
  texts.set(slug(m[1]), { text: m[1], slow: true });
  texts.set(slug(m[3]), { text: m[3], slow: false });
}
for (const f of ['src/screens/Talk.tsx', 'src/data/talkBoards.ts']) for (const m of readFileSync(f, 'utf8').matchAll(/\['([A-Za-z ]+)', '/g)) texts.set(slug(m[1]), { text: m[1], slow: true });
for (const f of ['src/data/extras.ts']) for (const m of readFileSync(f, 'utf8').matchAll(/word: '([^']+)'/g)) texts.set(slug(m[1]), { text: m[1], slow: false });
for (const m of readFileSync('src/data/curriculum.ts', 'utf8').matchAll(/twister: '([^']+)'/g)) texts.set(slug(m[1]), { text: m[1], slow: false });
const lv = await import('../src/data/levels.ts');
for (const it of lv.ALL_ITEMS) {
  const t = it.speakText ?? it.word;
  texts.set(slug(t), { text: t.replace(/^\//, '').replace(/\/$/, ''), slow: it.kind === 'syllable' || it.kind === 'phrase' });
  if (it.kind === 'story') for (const sent of t.split(/(?<=[.!?])\s+/)) texts.set(slug(sent), { text: sent, slow: false });
}
const phrases = ['Amazing! You said it so well!', 'So close! Great trying!', "Good try! Let's listen first, then try together.", 'Hi! I am Angel. Let us practise sounds together!', 'Tap the mic and say it!', 'Try again. You can do it!'];
for (const p of phrases) texts.set(slug(p), { text: p, slow: false });

const voiceLines = [];
let made = 0;
for (const [k, { text, slow }] of texts) {
  for (const variant of slow ? ['', '__slow'] : ['']) {
    const out = `assets/voice/${k}${variant}.m4a`;
    if (!existsSync(out)) {
      const aiff = `/tmp/aa_${k}${variant}.aiff`;
      execFileSync('say', ['-v', 'Samantha', '-r', variant ? '110' : '165', '-o', aiff, text]);
      execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '48000', '-c', '1', aiff, out]);
      made++;
    }
    voiceLines.push(`  '${k}${variant}': require('../../${out}'),`);
  }
}
// The recording script for a voice actor: one row per clip the app can play.
{
  const rows = [['file', 'speed', 'text']];
  for (const [k, { text, slow }] of texts) { rows.push([`${k}.m4a`, 'normal', text]); if (slow) rows.push([`${k}__slow.m4a`, 'slow', text]); }
  const csv = rows.map((r) => r.map((c) => `"${String(c).replace(/"/g, '""')}"`).join(',')).join('\n') + '\n';
  writeFileSync('store/briefs/voice-script.csv', csv);
}
writeFileSync('src/data/voiceMap.ts', `// Generated by scripts/build-assets.mjs. Replace any clip with a human recording of the same filename.\nexport const VOICE: Record<string, number> = {\n${voiceLines.join('\n')}\n};\n`);
console.log('voice clips', voiceLines.length, 'new', made);

// ---- emoji ----
const seg = new Intl.Segmenter('en', { granularity: 'grapheme' });
const emojis = new Set();
for (const { segment } of seg.segment(src)) {
  if (/\p{Extended_Pictographic}/u.test(segment) || /^[0-9#*]️?⃣$/.test(segment)) emojis.add(segment);
}
const cp = (s, keepFe0f) => [...s].map((c) => c.codePointAt(0).toString(16)).filter((h) => keepFe0f || h !== 'fe0f').join('-');
const lines = [];
let missing = [];
for (const e of emojis) {
  const names = [cp(e, false), cp(e, true)];
  // Prefer the 3D picture (assets/fluent, from scripts/build-fluent.mjs); otherwise the flat Twemoji one.
  if (existsSync(`assets/fluent/${names[0]}.png`)) { lines.push(`  '${e}': require('../../assets/fluent/${names[0]}.png'),`); continue; }
  let ok = null;
  for (const n of names) {
    const out = `assets/emoji/${n}.png`;
    if (existsSync(out)) { ok = n; break; }
    try {
      execFileSync('curl', ['-sfL', '-o', out, `https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/${n}.png`]);
      ok = n; break;
    } catch { try { execFileSync('rm', ['-f', out]); } catch {} }
  }
  if (ok) lines.push(`  '${e}': require('../../assets/emoji/${ok}.png'),`); else missing.push(e);
}
writeFileSync('src/data/emojiMap.ts', `// Generated by scripts/build-assets.mjs. 3D pictures: Microsoft Fluent Emoji, MIT licence. Flat fallback: Twemoji (c) Twitter/jdecked, CC-BY 4.0.\nexport const EMOJI: Record<string, number> = {\n${lines.join('\n')}\n};\n`);
console.log('emoji', lines.length, 'missing', missing.join(' '));
