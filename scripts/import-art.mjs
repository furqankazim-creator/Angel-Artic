// Turns the illustrations in assets/art into the app's picture map, and reports what is still missing.
// Usage: node scripts/import-art.mjs
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const files = existsSync('assets/art') ? readdirSync('assets/art').filter((f) => /\.(png|webp|jpg|jpeg)$/i.test(f)) : [];
const lines = files.map((f) => `  '${f.replace(/\.[^.]+$/, '')}': require('../../assets/art/${f}'),`);
writeFileSync('src/data/artMap.ts', `// Generated by scripts/import-art.mjs. Drop an illustration named <word>.png into assets/art and run the script.\nexport const ART: Record<string, number> = {\n${lines.join('\n')}\n};\n`);

const { WORDS } = await import('../src/data/sounds.ts');
const { BOARDS } = await import('../src/data/talkBoards.ts');
const need = new Set([...WORDS.map((w) => slug(w.word)), ...BOARDS.flatMap((b) => b.words.map((w) => slug(w[0])))]);
const have = new Set(files.map((f) => slug(f.replace(/\.[^.]+$/, ''))));
const missing = [...need].filter((k) => !have.has(k));
const extra = [...have].filter((k) => !need.has(k));
console.log(`illustrations: ${have.size} of ${need.size} words done (${Math.round((have.size / need.size) * 100)}%). The rest still use emoji.`);
if (extra.length) console.log('files that match no word (check the spelling):', extra.join(', '));
if (missing.length && missing.length < 40) console.log('missing:', missing.join(', '));
